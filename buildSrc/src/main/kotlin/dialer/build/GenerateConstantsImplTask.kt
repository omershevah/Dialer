package dialer.build

import java.io.File
import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction

/**
 * Replaces `java/com/android/dialer/constants/aospdialer/ConstantsImpl.java` when the app is built
 * with another application ID. Its content provider authorities follow the application ID, matching
 * the authorities [MergeAdditionalManifestsTask] writes into the manifest.
 */
@CacheableTask
abstract class GenerateConstantsImplTask : DefaultTask() {

    @get:Input
    abstract val applicationId: Property<String>

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val id = applicationId.get()
        val out = outputDir.get().asFile.apply {
            deleteRecursively()
            mkdirs()
        }
        File(out, "com/android/dialer/constants/ConstantsImpl.java").apply {
            parentFile.mkdirs()
            writeText(
                """
                // Generated by the Gradle build. Do not edit.
                package com.android.dialer.constants;

                import android.content.Context;
                import android.support.annotation.NonNull;
                import com.android.dialer.proguard.UsedByReflection;

                /** Provider config values for the standalone Dialer build ($id). */
                @UsedByReflection(value = "Constants.java")
                public class ConstantsImpl extends Constants {

                  @Override
                  @NonNull
                  public String getFilteredNumberProviderAuthority() {
                    return "$id.blocking.filterednumberprovider";
                  }

                  @Override
                  @NonNull
                  public String getFileProviderAuthority() {
                    return "$id.files";
                  }

                  @NonNull
                  @Override
                  public String getAnnotatedCallLogProviderAuthority() {
                    return "$id.annotatedcalllog";
                  }

                  @NonNull
                  @Override
                  public String getPhoneLookupHistoryProviderAuthority() {
                    return "$id.phonelookuphistory";
                  }

                  @NonNull
                  @Override
                  public String getPreferredSimFallbackProviderAuthority() {
                    return "$id.preferredsimfallback";
                  }

                  @Override
                  public String getUserAgent(Context context) {
                    return null;
                  }

                  @NonNull
                  @Override
                  public String getSettingsActivity() {
                    return "com.android.dialer.app.settings.DialerSettingsActivity";
                  }
                }
                """
                    .trimIndent() + "\n"
            )
        }
    }
}
